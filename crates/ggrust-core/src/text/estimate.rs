//! lets-plot's text width *estimator* (port of `TextMetricsEstimator`).
//!
//! Used only where lets-plot's decisions depend on it, namely how many axis breaks
//! fit, so ggrust picks the same breaks as lets-plot. Drawing and spacing use the
//! real font metrics in [`super::measure`].

use super::FontFace;

const DEFAULT_CHAR_WIDTH: f64 = 12.327791262135923;
const DEFAULT_FONT_SIZE: f64 = 14.0;
const FONT_WIDTH_SCALE_FACTOR: f64 = 0.85026;
const SIZE_COEFFICIENT: f64 = 0.9843304096547842;
/// lets-plot's "sans-serif" falls back to the Lucida Grande coefficient.
const FAMILY_ADDITIVE: f64 = 0.08777509389956582;
const CLUSTER_WIDTH: [f64; 5] = [
    6.440506329113925,
    10.181218274111677,
    12.583512544802868,
    14.536683417085428,
    17.714285714285715,
];

/// Estimated width in pixels of `text` at `size`, as lets-plot computes it.
pub fn estimated_width(text: &str, size: f64, face: FontFace) -> f64 {
    if text.is_empty() {
        return 0.0;
    }
    let face_additive = match face {
        FontFace::BoldItalic => 0.9172120995070999,
        FontFace::Bold => 0.6908238890181602,
        FontFace::Italic => 0.1783188620736738,
        FontFace::Plain => 0.0,
    };
    let mut predicted = 0.0;
    let mut length = 0.0;
    for character in text.chars() {
        predicted += cluster(character).map_or(DEFAULT_CHAR_WIDTH, |id| CLUSTER_WIDTH[id]);
        // Kotlin counts UTF-16 units.
        length += character.len_utf16() as f64;
    }
    let corrected = (predicted + length * (FAMILY_ADDITIVE + face_additive))
        * (SIZE_COEFFICIENT * size / DEFAULT_FONT_SIZE);
    FONT_WIDTH_SCALE_FACTOR * corrected
}

fn cluster(character: char) -> Option<usize> {
    CLUSTERS
        .binary_search_by(|(candidate, _)| candidate.cmp(&character))
        .ok()
        .map(|index| usize::from(CLUSTERS[index].1))
}

