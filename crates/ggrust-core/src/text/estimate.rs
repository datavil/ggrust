#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted() {
        assert!(CLUSTERS.windows(2).all(|pair| pair[0].0 < pair[1].0));
        assert_eq!(CLUSTERS.len(), 824);
    }

    #[test]
    fn typical_label_matches_lets_plot() {
        // lets-plot estimates "0000" at 13 px as 31.9 px (real Liberation Sans: 28.9).
        let width = estimated_width("0000", 13.0, FontFace::Plain);
        assert!((width - 31.9).abs() < 0.1, "{width}");
    }
}
