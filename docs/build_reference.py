def full_path(path: str) -> str:
    """Return the dotted import path of a section entry."""
    return path if "." in path else f"ggrust.{path}"


def resolve(path: str) -> object:
    """Import and return the object at a dotted path."""
    module_name, _, name = full_path(path).rpartition(".")
    return getattr(importlib.import_module(module_name), name)


def summary(path: str) -> str:
    """Return the first sentence block of an object's docstring, on one line."""
    docstring = inspect.getdoc(resolve(path)) or ""
    first_paragraph = docstring.split("\n\n", 1)[0]
    return " ".join(first_paragraph.split()).replace("|", "\\|")


def display_name(path: str) -> str:
    """Return the name shown for an entry: functions get `()`."""
    name = path.rpartition(".")[2]
    return f"{name}()" if inspect.isfunction(resolve(path)) else name


def object_page(path: str) -> str:
    """Return the Markdown of one object's page.

    When the docstring example binds ``plot``, the page ends with that plot, rendered
    by ``build_examples.py`` into ``docs/examples/figures/reference/<name>.html``.
    """
    name = path.rpartition(".")[2]
    page = (
        f"---\ntitle: {name}\n---\n\n::: {full_path(path)}\n    options:\n      heading_level: 1\n"
    )
    if build_examples.binds_plot(build_examples.docstring_example(resolve(path))):
        page += f'\n--8<-- "figures/reference/{name}.html"\n'
    return page


def overview_page() -> str:
    """Return the Markdown of the grouped overview."""
    lines = [
        "# API reference",
        "",
        "ggrust follows lets-plot's Python API. Every public name is listed here by",
        "topic; open one for its parameters and examples. The usual import is",
        "",
        "```python",
        "from ggrust import *",
        "```",
        "",
        "Missing something you use from lets-plot?",
        "[Open a feature request](https://github.com/datavil/ggrust/issues/new){ .md-button }",
        "",
    ]
    for section, (description, paths) in SECTIONS.items():
        lines += [f"## {section}", "", description, "", "| Name | Description |", "|---|---|"]
        for path in paths:
            name = path.rpartition(".")[2]
            lines.append(f"| [`{display_name(path)}`](api/{name}.md) | {summary(path)} |")
        lines.append("")
    return "\n".join(lines)


def nav() -> str:
    """Return the API reference block of the zensical.toml nav."""
    lines = ['  { "API reference" = [', '    "reference/index.md",']
    for section, (_, paths) in SECTIONS.items():
        lines.append(f'    {{ "{section}" = [')
        lines += [f'      "reference/api/{path.rpartition(".")[2]}.md",' for path in paths]
        lines.append("    ] },")
    lines.append("  ] },")
    return "\n".join(lines) + "\n"


def check_coverage() -> None:
    """Fail when a public name of ggrust is missing from the sections."""
    listed = {path.rpartition(".")[2] for _, paths in SECTIONS.values() for path in paths}
    missing = sorted(set(ggrust.__all__) - listed - {"__version__"})
    if missing:
        raise SystemExit(f"public names missing from SECTIONS: {', '.join(missing)}")


def main() -> None:
    """Write the overview, one page per object, and the nav."""
    check_coverage()
    shutil.rmtree(REFERENCE, ignore_errors=True)
    (REFERENCE / "api").mkdir(parents=True)
    (REFERENCE / "index.md").write_text(overview_page())
    for _, paths in SECTIONS.values():
        for path in paths:
            name = path.rpartition(".")[2]
            (REFERENCE / "api" / f"{name}.md").write_text(object_page(path))
    config = CONFIG.read_text()
    before, rest = config.split(NAV_START, 1)
    after = rest.split(NAV_END, 1)[1]
    CONFIG.write_text(before + NAV_START + nav() + NAV_END + after)


if __name__ == "__main__":
    main()
