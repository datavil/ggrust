"""Write the API reference: an overview page and one page per function or class.

The overview (``docs/reference/index.md``) groups every public name into sections,
each a table of names and one-line summaries, as on cellestial's and lets-plot's
API pages. Each name gets ``docs/reference/api/<name>.md``, rendered by mkdocstrings
from its docstring. The API part of the nav in ``zensical.toml`` is rewritten between
its marker comments.

The output is deterministic and committed. Run after adding a public name or changing
a summary line: ``uv run python docs/build_reference.py``. CI fails when the committed
pages are out of date.
"""

