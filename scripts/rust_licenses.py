"""Write the license texts of the Rust crates linked into the ggrust extension.

The wheel's binary statically links every normal (non-dev) dependency of the workspace,
and their MIT, BSD and Apache licenses ask that their notices ship with each binary copy.
This script reads ``cargo metadata`` (versions pinned by ``Cargo.lock``), collects each
crate's LICENSE, COPYING and NOTICE files from the cargo registry, and writes them to
``licenses/rust-dependencies.txt``, which ``pyproject.toml`` lists in ``license-files``.

Crates are listed for the six platforms the release workflow builds wheels for, so
one file covers every wheel. A crate whose package ships no license file gets the text
from its repository, kept in ``licenses/extra/`` (see ``EXTRA_LICENSES``).

Usage::

    python scripts/rust_licenses.py          # rewrite the file
    python scripts/rust_licenses.py --check  # fail when the file is out of date
"""

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "licenses" / "rust-dependencies.txt"
# The wheel targets of .github/workflows/release.yml.
WHEEL_TARGETS = (
    "x86_64-unknown-linux-gnu",
    "aarch64-unknown-linux-gnu",
    "x86_64-apple-darwin",
    "aarch64-apple-darwin",
    "x86_64-pc-windows-msvc",
    "aarch64-pc-windows-msvc",
)
# License texts of crates whose package ships none, copied from their repository.
EXTRA_LICENSES = {
    # https://github.com/kylebarron/arro3/blob/main/LICENSE_MIT
    "pyo3-arrow": [ROOT / "licenses" / "extra" / "pyo3-arrow-LICENSE_MIT"],
}
LICENSE_PREFIXES = ("license", "licence", "copying", "notice", "unlicense", "copyright")


def linked_packages(metadata: dict) -> list[dict]:
    """Return the non-workspace packages reachable through normal or build dependencies."""
    nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
    workspace = set(metadata["workspace_members"])
    seen: set[str] = set()
    stack = list(workspace)
    while stack:
        package_id = stack.pop()
        if package_id in seen:
            continue
        seen.add(package_id)
        for dependency in nodes[package_id]["deps"]:
            if any(kind["kind"] in (None, "build") for kind in dependency["dep_kinds"]):
                stack.append(dependency["pkg"])
    packages = [
        package
        for package in metadata["packages"]
        if package["id"] in seen and package["id"] not in workspace
    ]
    return sorted(packages, key=lambda package: (package["name"], package["version"]))


def license_files(package: dict) -> list[Path]:
    """Return the license and notice files shipped in a crate's source directory."""
    directory = Path(package["manifest_path"]).parent
    named = list(EXTRA_LICENSES.get(package["name"], []))
    if package.get("license_file"):
        named.append(directory / package["license_file"])
    for path in sorted(directory.iterdir()):
        if path.is_file() and path.name.lower().startswith(LICENSE_PREFIXES):
            named.append(path)
    unique: list[Path] = []
    for path in named:
        if path.is_file() and path.resolve() not in [item.resolve() for item in unique]:
            unique.append(path)
    return unique


def render(packages: list[dict]) -> tuple[str, list[str]]:
    """Return the notices text and the names of crates that ship no license file."""
    texts: dict[str, str] = {}
    users: dict[str, list[str]] = {}
    missing: list[str] = []
    header_lines = []
    for package in packages:
        label = f"{package['name']} {package['version']}"
        files = license_files(package)
        if not files:
            missing.append(label)
        digests = []
        for path in files:
            text = path.read_text(encoding="utf-8", errors="replace").strip()
            digest = hashlib.sha256(text.encode()).hexdigest()[:12]
            texts.setdefault(digest, text)
            users.setdefault(digest, []).append(label)
            digests.append(digest)
        source = package.get("repository") or "https://crates.io/crates/" + package["name"]
        refs = ", ".join(f"[{digest}]" for digest in digests) or "(no license file in crate)"
        header_lines.append(f"{label}  {package.get('license') or 'unknown'}  {source}  {refs}")
    parts = [
        "Third-party Rust crates linked into the ggrust extension module",
        "",
        "Generated by scripts/rust_licenses.py from Cargo.lock. Do not edit by hand.",
        "Each crate lists its SPDX license and the license texts it ships, by id.",
        "",
        *header_lines,
    ]
    for digest, text in texts.items():
        parts += [
            "",
            "=" * 79,
            f"[{digest}] used by: {', '.join(users[digest])}",
            "=" * 79,
            "",
            text,
        ]
    return "\n".join(parts) + "\n", missing


def main() -> int:
    """Write or check the license file; return the process exit code."""
    metadata = json.loads(
        subprocess.run(
            [
                "cargo",
                "metadata",
                "--format-version",
                "1",
                "--locked",
                *(
                    argument
                    for target in WHEEL_TARGETS
                    for argument in ("--filter-platform", target)
                ),
            ],
            cwd=ROOT,
            check=True,
            capture_output=True,
            text=True,
        ).stdout
    )
    text, missing = render(linked_packages(metadata))
    if missing:
        print("crates without a license file (add their text by hand):", *missing, sep="\n  ")
    if "--check" in sys.argv:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print(
                f"{OUTPUT.relative_to(ROOT)} is out of date; run: python scripts/rust_licenses.py"
            )
            return 1
        return 0
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(text) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
