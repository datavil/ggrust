"""Hierarchical clustering and dendrograms (``hclust``, ``geom_dendrogram``,
``scale_*_dendro`` + ``guide_axis_dendro``).

``hclust`` is checked against base R's ``hclust`` on the matrices of
``tests/fixtures/hclust_reference.json`` (generated by
``tests/fixtures/generate_hclust_reference.R``): same merges and leaf order, ties
included, and heights within rounding. The axis dendrogram is checked on the drawn
SVG: the tree's leaves sit at their categories' ticks, the root lies outward, the
axis follows the tree's order, and bad input raises typed errors.
"""

from __future__ import annotations

import itertools
import json
import re
import warnings
from pathlib import Path

import ggrust as gg
import polars as pl
import pytest
from ggrust.errors import DataError, SpecError, UnsupportedValueError

REFERENCE: list[dict[str, object]] = json.loads(
    (Path(__file__).parent / "fixtures" / "hclust_reference.json").read_text()
)
SCIPY: list[dict[str, object]] = json.loads(
    (Path(__file__).parent / "fixtures" / "scipy_dendrogram_reference.json").read_text()
)

GENES = pl.DataFrame(
    {
        "gene": ["CD3E", "CD8A", "CD4", "MS4A1", "CD79A", "LYZ", "CD14"],
        "T": [5.1, 4.8, 4.2, 0.2, 0.1, 0.3, 0.2],
        "B": [0.3, 0.2, 0.4, 5.5, 5.9, 0.4, 0.1],
        "Mono": [0.2, 0.1, 1.1, 0.3, 0.2, 6.2, 5.8],
        "NK": [2.2, 3.9, 0.3, 0.1, 0.2, 0.5, 0.3],
    }
)
LONG = GENES.unpivot(index="gene", variable_name="cell_type", value_name="expression")


def _frame(matrix: list[list[float]]) -> dict[str, list[float]]:
    """Columns ``c0``, ``c1``, ... of a row-major matrix."""
    return {f"c{column}": [row[column] for row in matrix] for column in range(len(matrix[0]))}


@pytest.mark.parametrize(
    "case", REFERENCE, ids=lambda case: f"{case['name']}-{case['method']}-{case['distance']}"
)
def test_hclust_matches_r(case: dict[str, object]) -> None:
    matrix = case["matrix"]
    assert isinstance(matrix, list)
    tree = gg.hclust(_frame(matrix), method=case["method"], distance=case["distance"])
    assert [list(pair) for pair in tree.merge] == case["merge"]
    assert [leaf + 1 for leaf in tree.order] == case["order"]
    assert tree.height == pytest.approx(case["height"], rel=1e-9, abs=1e-12)
    assert tree.labels == tuple(str(index) for index in range(1, len(matrix) + 1))


def test_labels_and_columns() -> None:
    rows = gg.hclust(GENES, labels="gene", method="average", distance="correlation")
    assert set(rows.ordered_labels) == set(GENES["gene"])
    assert rows.method == "average"
    columns = gg.hclust(GENES, labels="gene", axis="columns")
    assert set(columns.labels) == {"T", "B", "Mono", "NK"}
    # Clustering the columns is clustering the transposed rows.
    transposed = {gene: list(GENES.row(row)[1:]) for row, gene in enumerate(GENES["gene"])}
    assert gg.hclust(transposed).merge == columns.merge
    numbers = gg.hclust({"id": [10, 20, 30], "v": [0.0, 1.0, 9.0]}, labels="id")
    assert numbers.labels == ("10", "20", "30")


def test_from_linkage_takes_an_explicit_order() -> None:
    linkage = [[0, 1, 1.0, 2], [2, 3, 1.5, 2], [4, 5, 4.0, 4]]
    tree = gg.ClusterTree.from_linkage(linkage, ["a", "b", "c", "d"])
    assert tree.merge == ((-1, -2), (-3, -4), (1, 2))
    flipped = gg.ClusterTree.from_linkage(linkage, ["a", "b", "c", "d"], order=[2, 3, 1, 0])
    assert flipped.ordered_labels == ("c", "d", "b", "a")


Link = tuple[tuple[float, ...], tuple[float, ...]]


def _scipy_links(case: dict[str, object]) -> list[Link]:
    """SciPy's ``icoord``/``dcoord`` links, leaves moved from 5, 15, ... to 0, 1, ..."""
    icoord, dcoord = case["icoord"], case["dcoord"]
    assert isinstance(icoord, list) and isinstance(dcoord, list)
    return sorted(
        (tuple(round((x - 5) / 10, 9) for x in xs), tuple(round(y, 9) for y in ys))
        for xs, ys in zip(icoord, dcoord, strict=True)
    )


def _ggrust_links(tree: gg.ClusterTree) -> list[Link]:
    """Links of ``geom_dendrogram``: per merge, the left drop, left half, right drop
    and right half, as SciPy's four corners."""
    data = gg.geom_dendrogram(tree).as_dict()["data"]
    links = []
    for start in range(0, len(data["x"]), 4):
        left, right = start, start + 2
        xs = (data["x"][left], data["x"][left], data["x"][right], data["x"][right])
        ys = (data["yend"][left], data["y"][left], data["y"][right], data["yend"][right])
        links.append((tuple(round(x, 9) for x in xs), tuple(round(y, 9) for y in ys)))
    return sorted(links)


@pytest.mark.parametrize("case", SCIPY, ids=lambda case: str(case["name"]))
def test_scipy_linkage_keeps_scipy_order_and_coordinates(case: dict[str, object]) -> None:
    labels = case["labels"]
    assert isinstance(labels, list)
    tree = gg.ClusterTree.from_linkage(case["linkage"], labels)  # type: ignore[arg-type]
    assert list(tree.order) == case["leaves"]
    # scanpy's `categories_ordered` is SciPy's `ivl`.
    assert list(tree.ordered_labels) == case["ivl"]
    assert _ggrust_links(tree) == _scipy_links(case)


def test_scipy_tree_orders_the_axis() -> None:
    case = next(case for case in SCIPY if case["name"] == "scanpy_like")
    labels = case["labels"]
    assert isinstance(labels, list)
    tree = gg.ClusterTree.from_linkage(case["linkage"], labels)  # type: ignore[arg-type]
    frame = {"group": labels, "value": list(range(len(labels)))}
    plot = gg.ggplot(frame, gg.aes("value", "group")) + gg.geom_point() + gg.scale_y_dendro(tree)
    found = re.findall(r'y="([\d.]+)"[^>]*>([^<]+)</text>', _axis_group(plot.to_svg(), "y"))
    by_height = [name for _, name in sorted(found, key=lambda item: -float(item[0]))]
    assert by_height == case["ivl"]


LINKAGE = [[0, 1, 1.0, 2], [2, 3, 4.0, 3]]


@pytest.mark.parametrize(
    ("linkage", "labels", "path", "message"),
    [
        (LINKAGE[:1], ["a", "b", "c"], "linkage", "3 labels need a linkage of 2 rows, got 1"),
        ([[0, 1, 1.0], [2, 3, 4.0, 3]], ["a", "b", "c"], "linkage[0]", "4 values, got 3"),
        ([[0, 1.5, 1.0, 2], [2, 3, 4.0, 3]], ["a", "b", "c"], "linkage[0][1]", "integer index"),
        ([[0, 4, 1.0, 2], [2, 3, 4.0, 3]], ["a", "b", "c"], "linkage[0][1]", "earlier cluster"),
        ([[0, 1, 1.0, 2], [0, 3, 4.0, 3]], ["a", "b", "c"], "linkage[1][0]", "merged twice"),
        ([[0, 1, 5.0, 2], [2, 3, 4.0, 3]], ["a", "b", "c"], "linkage[1][2]", "must not decrease"),
        ([[0, 1, float("nan"), 2], [2, 3, 4.0, 3]], ["a", "b", "c"], "linkage[0][2]", "0 or more"),
        ([[0, 1, 1.0, 2], [2, 3, 4.0, 2]], ["a", "b", "c"], "linkage[1][3]", "3 leaves"),
        (LINKAGE, ["a", "b", "a"], "labels", "appears twice"),
        ([], [], "labels", "at least one leaf"),
    ],
)
def test_bad_linkage_names_the_entry(
    linkage: list[list[float]], labels: list[str], path: str, message: str
) -> None:
    with pytest.raises(SpecError, match=re.escape(message)) as caught:
        gg.ClusterTree.from_linkage(linkage, labels)
    assert caught.value.path == path


def test_geom_dendrogram_segments() -> None:
    tree = gg.hclust({"v": [0.0, 1.0, 5.0]})
    layer = gg.geom_dendrogram(tree).as_dict()
    assert layer["geom"] == "segment"
    data = layer["data"]
    # Two merges, four segments each; leaves at 0..n-1, root at the top height.
    assert len(data["x"]) == 8
    assert sorted({*data["x"], *data["xend"]})[0] == 0.0
    assert max(data["y"]) == tree.height[-1]
    triangle = gg.geom_dendrogram(tree, type="triangle", orientation="y").as_dict()["data"]
    assert len(triangle["y"]) == 4
    assert max(triangle["x"]) == tree.height[-1]


def _axis_group(svg: str, axis: str) -> str:
    match = re.search(rf'<g class="axis-{axis}">(.*?)</g>', svg, re.S)
    assert match is not None
    return match.group(1)


def _tree_group(svg: str, axis: str) -> str:
    """The paths of the ``dendrogram-{axis}`` group (empty without one)."""
    match = re.search(rf'<g class="dendrogram-{axis}"[^>]*>(.*?)</g>', svg, re.S)
    return match.group(1) if match else ""


def _segments(group: str) -> list[tuple[float, float, float, float]]:
    """Every straight piece of the group's open paths (polylines split up)."""
    segments = []
    for data in re.findall(r'<path d="(M[-\d. L]+)"', group):
        numbers = [float(value) for value in re.findall(r"-?\d+(?:\.\d+)?", data)]
        points = list(zip(numbers[::2], numbers[1::2], strict=True))
        segments.extend((*start, *end) for start, end in itertools.pairwise(points))
    return segments


def _heatmap(**guide: object) -> gg.PlotSpec:
    rows = gg.hclust(GENES, labels="gene")
    columns = gg.hclust(GENES, labels="gene", axis="columns")
    return (
        gg.ggplot(LONG, gg.aes("cell_type", "gene", fill="expression"))
        + gg.geom_tile()
        + gg.scale_y_dendro(rows, guide=gg.guide_axis_dendro(**guide))
        + gg.scale_x_dendro(columns)
        + gg.theme(axis_ticks=gg.element_blank())
    )


def test_axis_follows_the_tree_and_leaves_meet_the_ticks() -> None:
    rows = gg.hclust(GENES, labels="gene")
    svg = _heatmap().to_svg()
    y_group = _axis_group(svg, "y")
    labels = re.findall(r'y="([\d.]+)"[^>]*>([^<]+)</text>', y_group)
    # Bottom to top is the tree's order.
    by_height = [name for _, name in sorted(labels, key=lambda item: -float(item[0]))]
    assert tuple(by_height) == rows.ordered_labels
    segments = _segments(_tree_group(svg, "y"))
    assert len(segments) == 3 * (len(rows.labels) - 1)
    label_left = min(float(x) for x in re.findall(r'<text x="([\d.]+)"', y_group))
    leaves_x = max(max(start_x, end_x) for start_x, _, end_x, _ in segments)
    root_x = min(min(start_x, end_x) for start_x, _, end_x, _ in segments)
    # Leaves past the labels, root 40 px further out.
    assert leaves_x < label_left
    assert leaves_x - root_x == pytest.approx(40, abs=0.05)
    # Every label has a leaf stub at its height.
    stub_heights = {
        round(y, 1)
        for start_x, start_y, end_x, end_y in segments
        for x, y in ((start_x, start_y), (end_x, end_y))
        if x == leaves_x
    }
    label_heights = {round(float(y) - 4.5, 1) for y, _ in labels}
    assert len(stub_heights) == len(labels)
    assert all(any(abs(stub - label) < 1.5 for label in label_heights) for stub in stub_heights)
    x_group = _axis_group(svg, "x")
    label_bottom = max(float(y) for y in re.findall(r'<text x="[\d.]+" y="([\d.]+)"', x_group))
    below = [
        segment
        for segment in _segments(_tree_group(svg, "x"))
        if min(segment[1], segment[3]) > label_bottom
    ]
    assert len(below) == 3 * 3


def test_opposite_side_and_space() -> None:
    svg = _heatmap(side="opposite", space=60).to_svg()
    panel = re.search(r'<rect x="([\d.]+)" y="([\d.]+)" width="([\d.]+)"', svg)
    assert panel is not None
    segments = _segments(_tree_group(svg, "y"))
    left = min(min(start_x, end_x) for start_x, _, end_x, _ in segments)
    right = max(max(start_x, end_x) for start_x, _, end_x, _ in segments)
    assert right - left == pytest.approx(60, abs=0.05)
    labels_x = [float(x) for x in re.findall(r'<text x="([\d.]+)"', _axis_group(svg, "y"))]
    assert left > max(labels_x)


def test_reverse_flips_the_tree() -> None:
    rows = gg.hclust(GENES, labels="gene")
    plot = (
        gg.ggplot(LONG, gg.aes("cell_type", "gene", fill="expression"))
        + gg.geom_tile()
        + gg.scale_y_dendro(rows, reverse=True)
    )
    labels = re.findall(r'y="([\d.]+)"[^>]*>([^<]+)</text>', _axis_group(plot.to_svg(), "y"))
    by_height = [name for _, name in sorted(labels, key=lambda item: float(item[0]))]
    assert tuple(by_height) == rows.ordered_labels


def test_facets_warn_and_keep_the_order() -> None:
    rows = gg.hclust(GENES, labels="gene")
    plot = (
        gg.ggplot(LONG, gg.aes("cell_type", "gene", fill="expression"))
        + gg.geom_tile()
        + gg.scale_y_dendro(rows)
        + gg.facet_wrap("cell_type")
    )
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        svg = plot.to_svg()
    assert any("faceted plots draw no dendrogram" in str(item.message) for item in caught)
    assert _tree_group(svg, "y") == ""


def test_numbers_pass_through_a_dendrogram_axis() -> None:
    # geom_dendrogram's segments are numbers at the leaf positions: a dendro scale
    # labels them.
    tree = gg.hclust(GENES, labels="gene")
    plot = gg.ggplot() + gg.geom_dendrogram(tree, orientation="y") + gg.scale_y_dendro(tree)
    labels = re.findall(r'y="([\d.]+)"[^>]*>([^<]+)</text>', _axis_group(plot.to_svg(), "y"))
    by_height = [name for _, name in sorted(labels, key=lambda item: -float(item[0]))]
    assert tuple(by_height) == tree.ordered_labels


@pytest.mark.parametrize(
    ("call", "error", "message"),
    [
        (lambda: gg.hclust(GENES, labels="gene", method="ward"), SpecError, "ward.D2"),
        (lambda: gg.hclust(GENES, labels="gene", distance="cosine"), SpecError, "euclidean"),
        (lambda: gg.hclust(GENES, labels="gene", axis="both"), SpecError, "rows"),
        (lambda: gg.hclust(GENES), DataError, "column 'gene' is not numeric"),
        (
            lambda: gg.hclust(GENES.with_columns(T=pl.lit(None, pl.Float64)), labels="gene"),
            DataError,
            "column 'T' has a missing or infinite value at 'CD3E'",
        ),
        (
            lambda: gg.hclust({"g": ["a", "a"], "v": [1.0, 2.0]}, labels="g"),
            DataError,
            "label 'a' names two rows",
        ),
        (
            lambda: gg.hclust(
                {"v": [1.0, 2.0], "w": [3.0, 3.0]}, axis="columns", distance="correlation"
            ),
            DataError,
            "'w' by correlation",
        ),
        (lambda: gg.scale_y_dendro(["a", "b"]), UnsupportedValueError, "ggrust.hclust()"),
        (
            lambda: gg.scale_y_dendro(gg.hclust({"v": [1.0, 2.0]}), guide="legend"),
            SpecError,
            "axis_dendro",
        ),
        (lambda: gg.guide_axis_dendro(space=-1), UnsupportedValueError, "0 or more"),
        (lambda: gg.guide_axis_dendro(side="top"), SpecError, "opposite"),
        (
            lambda: gg.geom_dendrogram(gg.hclust({"v": [1.0, 2.0]}), type="arc"),
            SpecError,
            "triangle",
        ),
    ],
)
def test_bad_input_fails_early(call: object, error: type[Exception], message: str) -> None:
    with pytest.raises(error, match=re.escape(message)):
        call()  # type: ignore[operator]


def test_engine_checks_levels_and_trees() -> None:
    rows = gg.hclust(GENES.filter(pl.col("gene") != "CD14"), labels="gene")
    plot = gg.ggplot(LONG, gg.aes("cell_type", "gene", fill="expression")) + gg.geom_tile()
    with pytest.raises(SpecError, match="'CD14' is on the y axis but not a leaf"):
        (plot + gg.scale_y_dendro(rows)).to_svg()
    full = gg.hclust(GENES, labels="gene")
    with pytest.raises(SpecError, match="limits conflict with the dendrogram"):
        (plot + gg.scale_y_dendro(full) + gg.scale_y_discrete(limits=["CD4"])).to_svg()
    numbers = gg.ggplot({"x": [1.0, 2.0], "y": [1.0, 2.0]}, gg.aes("x", "y")) + gg.geom_point()
    broken = gg.ClusterTree(("a", "b"), ((-1, -1),), (1.0,), (0, 1))
    with pytest.raises(SpecError, match="merged twice") as caught:
        (numbers + gg.scale_x_dendro(broken)).to_svg()
    assert caught.value.path == "scales[0].dendrogram.merge[0]"
