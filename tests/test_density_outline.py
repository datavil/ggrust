"""``density_outline()`` matches scipy's ``gaussian_kde`` + scikit-image's ``find_contours``.

Reference: ``tests/fixtures/density_outline_scipy.json`` (generated by
``tests/fixtures/generate_density_outline_reference.py`` with scipy 1.17 and
scikit-image 0.26): per contour the vertex count exactly, the end vertices and a
summary of x and y within 1e-12 of the data span. On arm64 macOS the vertices are
bit-identical with a fixed bandwidth factor and within about 1e-14 of the span with
Scott's or Silverman's rule (scipy's ``neff`` is an Accelerate ``ddot``).
"""

from __future__ import annotations

import importlib.util
import json
import math
from pathlib import Path
from types import ModuleType
from typing import Any

import numpy as np
import polars as pl
import pytest
from ggrust import density_outline
from ggrust.errors import SpecError

FIXTURES = Path(__file__).parent / "fixtures"
TOLERANCE = 1e-12


def _generator() -> ModuleType:
    """The fixture generator, for its ``case_inputs()`` and ``summarize_contour()``."""
    spec = importlib.util.spec_from_file_location(
        "generate_density_outline_reference", FIXTURES / "generate_density_outline_reference.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


GENERATOR = _generator()
REFERENCE: dict[str, Any] = json.loads((FIXTURES / "density_outline_scipy.json").read_text())
CASES = {name: (points, options) for name, points, options in GENERATOR.case_inputs()}


def _contours(outline: pl.DataFrame) -> list[np.ndarray]:
    """The outline's paths as ``(n, 2)`` arrays, in path order."""
    return [
        group.select("x", "y").to_numpy()
        for _, group in outline.sort("path", maintain_order=True).group_by(
            "path", maintain_order=True
        )
    ]


@pytest.mark.parametrize("case", REFERENCE["cases"], ids=lambda case: case["name"])
def test_matches_scipy_and_skimage(case: dict[str, Any]) -> None:
    points, options = CASES[case["name"]]
    outline = density_outline(points, **options)
    assert outline.schema == {"x": pl.Float64, "y": pl.Float64, "path": pl.UInt32}
    contours = _contours(outline)
    assert len(contours) == len(case["contours"])
    finite = points[np.isfinite(points).all(axis=1)]
    span = finite.max(axis=0) - finite.min(axis=0)
    for contour, expected in zip(contours, case["contours"], strict=True):
        actual = GENERATOR.summarize_contour(contour)
        assert actual["n"] == expected["n"]
        for end in ("first", "last"):
            for axis in (0, 1):
                assert abs(actual[end][axis] - expected[end][axis]) <= TOLERANCE * span[axis]
        n = actual["n"]
        for axis, name in enumerate(("x", "y")):
            got, want = actual[name], expected[name]
            scale = TOLERANCE * span[axis]
            # sums of n values each off by at most `scale` (sum of squares: by 2|v| scale)
            assert abs(got["sum"] - want["sum"]) <= n * scale, name
            magnitude = math.sqrt(want["sum_squares"] * n)
            assert abs(got["sum_squares"] - want["sum_squares"]) <= 2 * magnitude * scale, name
            assert abs(got["weighted_sum"] - want["weighted_sum"]) <= n * n * scale, name
            for (index, value), (expected_index, expected_value) in zip(
                got["samples"], want["samples"], strict=True
            ):
                assert index == expected_index
                assert abs(value - expected_value) <= scale, (name, index)


def test_closed_outlines_repeat_their_first_vertex() -> None:
    points, options = CASES["ring"]
    contours = _contours(density_outline(points, **options))
    assert len(contours) == 2
    for contour in contours:
        assert np.array_equal(contour[0], contour[-1])


def test_inputs_frames_lists_and_masks() -> None:
    points, _ = CASES["five_points"]
    expected = density_outline(points, grid_size=40)
    assert density_outline(points.tolist(), grid_size=40).equals(expected)
    frame = pl.DataFrame({"a": points[:, 0], "b": points[:, 1]})
    assert density_outline(frame, grid_size=40).equals(expected)
    with_masked = np.ma.masked_array(
        np.vstack([points, [[0.0, 0.0]]]), mask=[[False, False]] * 5 + [[True, False]]
    )
    assert density_outline(with_masked, grid_size=40).equals(expected)
    with_nan = np.vstack([[[math.nan, 1.0]], points, [[2.0, math.inf]]])
    assert density_outline(with_nan, grid_size=40).equals(expected)


def test_level_never_crossed_gives_an_empty_frame() -> None:
    points, _ = CASES["five_points"]
    # a very wide kernel: the density stays above half its peak on the whole grid
    outline = density_outline(points, level=0.5, padding=0, bandwidth=50.0, grid_size=10)
    assert outline.height == 0
    assert outline.columns == ["x", "y", "path"]


@pytest.mark.parametrize(
    ("arguments", "path", "message"),
    [
        ({"points": [[0, 1, 2]] * 10}, "points", "row 0 must hold 2 values"),
        ({"points": [["a", 1]] * 10}, "points", "holds str 'a'"),
        ({"points": 3}, "points", "expected an (n, 2) array"),
        ({"points": [[10**400, 1]] * 10}, "points", "too large for a float"),
        ({"points": [[0.0, 1.0], [1.0, 0.0]]}, "points", "more than 2 finite points"),
        ({"points": [[float(i), 2.0 * i] for i in range(10)]}, "points", "singular"),
        ({"level": 0}, "level", "between 0 and 1"),
        ({"level": 1.5}, "level", "between 0 and 1"),
        ({"level": "0.1"}, "level", "expected a number"),
        ({"padding": -1}, "padding", "at least 0"),
        ({"padding": math.nan}, "padding", "at least 0"),
        ({"grid_size": 1}, "grid_size", "from 2 to 3162"),
        ({"grid_size": 2.5}, "grid_size", "from 2 to 3162"),
        ({"grid_size": 10**6}, "grid_size", "from 2 to 3162"),
        ({"bandwidth": "scot"}, "bandwidth", "unknown bandwidth rule 'scot'"),
        ({"bandwidth": -0.5}, "bandwidth", "positive finite"),
        ({"bandwidth": True}, "bandwidth", "expected a number"),
        ({"bandwidth": 1e-200}, "bandwidth", "too small or too large"),
        ({"points": [[1e200 * i, 1e200 * (i % 3)] for i in range(10)]}, "points", "overflows"),
        ({"padding": 1.7e308}, "padding", "overflows"),
    ],
)
def test_errors(arguments: dict[str, Any], path: str, message: str) -> None:
    points, _ = CASES["five_points"]
    call: dict[str, Any] = {"points": points, "grid_size": 20} | arguments
    with pytest.raises(SpecError) as error:
        density_outline(call.pop("points"), **call)
    assert error.value.path == path
    assert message in str(error.value)
