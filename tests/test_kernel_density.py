"""``kernel_density()`` matches scipy's 1D ``gaussian_kde``.

Reference: ``tests/fixtures/kernel_density_scipy.json`` (generated by
``tests/fixtures/generate_kernel_density_reference.py`` with scipy 1.17). Every
density is within 1e-12 of the case's peak density and within 1e-12 relative where
it is not tiny. On arm64 macOS the gap is about 1e-15 of the peak: scipy's variance
is an Accelerate ``ddot`` whose summation order ggrust does not reproduce.
"""

from __future__ import annotations

import importlib.util
import json
import math
from pathlib import Path
from types import ModuleType
from typing import Any

import numpy as np
import polars as pl
import pytest
from ggrust import kernel_density
from ggrust.errors import SpecError

FIXTURES = Path(__file__).parent / "fixtures"
TOLERANCE = 1e-12


def _generator() -> ModuleType:
    """The fixture generator, for its ``case_inputs()``."""
    spec = importlib.util.spec_from_file_location(
        "generate_kernel_density_reference", FIXTURES / "generate_kernel_density_reference.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


GENERATOR = _generator()
REFERENCE: dict[str, Any] = json.loads((FIXTURES / "kernel_density_scipy.json").read_text())
CASES = {name: (values, at, bandwidth) for name, values, at, bandwidth in GENERATOR.case_inputs()}


@pytest.mark.parametrize("case", REFERENCE["cases"], ids=lambda case: case["name"])
def test_matches_scipy(case: dict[str, Any]) -> None:
    values, at, bandwidth = CASES[case["name"]]
    result = kernel_density(values, at, bandwidth=bandwidth)
    assert result.schema == {"x": pl.Float64, "density": pl.Float64}
    np.testing.assert_array_equal(result["x"].to_numpy(), at.astype(np.float64))
    density = result["density"].to_numpy()
    expected = np.array(case["density"])
    assert density.shape == expected.shape
    peak = expected.max()
    assert np.max(np.abs(density - expected)) <= TOLERANCE * peak
    sizable = expected > 1e-6 * peak
    relative = np.abs(density - expected)[sizable] / expected[sizable]
    assert np.max(relative) <= TOLERANCE


def test_inputs_as_lists_series_and_numpy_agree() -> None:
    values = [0.3, 1.2, 1.9, 2.4, 4.0, 4.4]
    at = [0.0, 1.0, 2.5, 5.0]
    from_list = kernel_density(values, at)
    from_numpy = kernel_density(np.array(values), np.array(at))
    from_series = kernel_density(pl.Series(values), pl.Series(at))
    assert from_list.equals(from_numpy)
    assert from_list.equals(from_series)


def test_missing_and_non_finite_values_are_dropped() -> None:
    clean = kernel_density([1.0, 2.0, 4.5], [2.0])
    with_gaps = kernel_density(pl.Series([1.0, None, 2.0, float("nan"), 4.5]), [2.0])
    assert with_gaps.equals(clean)
    result = kernel_density([1.0, 2.0, 4.5], [2.0, float("nan"), None])
    density = result["density"].to_list()
    assert density[0] == clean["density"][0]
    assert math.isnan(density[1]) and math.isnan(density[2])


def test_booleans_count_as_zero_and_one() -> None:
    as_numbers = kernel_density([1.0, 0.0, 1.0], [0.5])
    assert kernel_density([True, False, True], [0.5]).equals(as_numbers)
    # The validating fallback (reached through a None) agrees with the fast path.
    assert kernel_density([True, False, None, True], [0.5]).equals(as_numbers)


def test_far_from_zero_loses_digits_with_the_offset() -> None:
    """Data offset by k standard deviations: the error grows with k (as in scipy)."""
    values = [1e6 + math.sin(i * 0.9) for i in range(300)]
    grid = np.linspace(1e6 - 3, 1e6 + 3, 101)
    centered = kernel_density([value - 1e6 for value in values], grid - 1e6)["density"]
    shifted = kernel_density(values, grid)["density"]
    gap = (shifted - centered).abs().max() / centered.max()
    assert gap < 1e6 * 1e-14


def test_density_integrates_to_one_and_bandwidth_widens() -> None:
    values = [math.sin(i * 0.7) * (1 + i % 3) for i in range(80)]
    grid = np.linspace(-12, 12, 4001)
    density = kernel_density(values, grid)["density"].to_numpy()
    assert abs(density.sum() * (grid[1] - grid[0]) - 1) < 1e-9
    narrow = kernel_density(values, [0.0], bandwidth=0.05)["density"][0]
    wide = kernel_density(values, [0.0], bandwidth=5.0)["density"][0]
    assert narrow != wide
    assert kernel_density(values, [])["density"].len() == 0


@pytest.mark.parametrize(
    ("values", "at", "bandwidth", "path", "message"),
    [
        ([2.0, 2.0, 2.0], [2.0], "scott", "values", "all equal"),
        ([2.0, float("nan")], [2.0], "scott", "values", "at least 2"),
        ([[1.0, 2.0], [3.0, 4.0]], [1.0], "scott", "values", "entry 0 is list"),
        ([1.0, 2.0], ["a"], "scott", "at", "entry 0 is str"),
        ([1.0, 2.0], 5.0, "scott", "at", "one-dimensional sequence"),
        ([1.0, 2.0], [1.0], "scot", "bandwidth", "unknown bandwidth rule 'scot'"),
        ([1.0, 2.0], [1.0], -1.0, "bandwidth", "positive finite"),
        ([1.0, 2.0], [1.0], True, "bandwidth", "expected 'scott'"),
        ([1.0, 2.0], [1.0], 1e-320, "bandwidth", "too small"),
        ([1.0, 2.0], [1.0], 10**400, "bandwidth", "too large for a float"),
    ],
)
def test_errors_name_the_argument(
    values: object, at: object, bandwidth: Any, path: str, message: str
) -> None:
    with pytest.raises(SpecError, match=message) as error:
        kernel_density(values, at, bandwidth=bandwidth)  # ty: ignore[invalid-argument-type]
    assert error.value.path == path
