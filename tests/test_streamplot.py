"""``streamplot()`` matches matplotlib's ``streamplot`` exactly.

Reference: ``tests/fixtures/streamplot_matplotlib.json`` (generated by
``tests/fixtures/generate_streamplot_reference.py`` with matplotlib 3.10): per line
the vertex count, first and last vertex and coordinate sums; every arrow in full.
The port is line by line, so the values are compared for equality.
"""

from __future__ import annotations

import importlib.util
import json
import math
from pathlib import Path
from types import ModuleType
from typing import Any

import numpy as np
import polars as pl
import pytest
from ggrust import aes, arrow, coord_fixed, geom_path, geom_segment, ggplot, streamplot
from ggrust.errors import SpecError

FIXTURES = Path(__file__).parent / "fixtures"


def _generator() -> ModuleType:
    """The fixture generator, for its ``case_fields()``."""
    spec = importlib.util.spec_from_file_location(
        "generate_streamplot_reference", FIXTURES / "generate_streamplot_reference.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


REFERENCE: dict[str, Any] = json.loads((FIXTURES / "streamplot_matplotlib.json").read_text())
CASES = {name: (field, options) for name, field, options in _generator().case_fields()}


@pytest.mark.parametrize("case", REFERENCE["cases"], ids=lambda case: case["name"])
def test_matches_matplotlib(case: dict[str, Any]) -> None:
    field, options = CASES[case["name"]]
    streams = streamplot(field["x"], field["y"], field["u"], field["v"], **options)
    lines = streams.lines.partition_by("group", maintain_order=True)
    assert len(lines) == len(case["lines"])
    for line, expected in zip(lines, case["lines"], strict=True):
        x = line["x"].to_numpy()
        y = line["y"].to_numpy()
        summary = [len(x), x[0], y[0], x[-1], y[-1], *np.sum(np.column_stack([x, y]), axis=0)]
        assert summary == pytest.approx(expected, rel=1e-12, abs=1e-12)
    arrows = streams.arrows.select("x", "y", "xend", "yend").rows()
    assert [list(row) for row in arrows] == [
        pytest.approx(row, rel=1e-12, abs=1e-12) for row in case["arrows"]
    ]


def test_frames_and_meshgrid_input() -> None:
    x = np.linspace(-3, 3, 50)
    y = np.linspace(-2, 2, 40)
    grid_x, grid_y = np.meshgrid(x, y)
    from_vectors = streamplot(x, y, -grid_y, grid_x)
    from_meshgrid = streamplot(grid_x, grid_y, (-grid_y).tolist(), grid_x)
    assert from_vectors.lines.equals(from_meshgrid.lines)
    assert from_vectors.arrows.equals(from_meshgrid.arrows)
    assert from_vectors.lines.schema == pl.Schema(
        {"x": pl.Float64, "y": pl.Float64, "group": pl.UInt32}
    )
    assert from_vectors.arrows.columns == ["x", "y", "xend", "yend", "group"]
    # one arrow per line, on its own group
    assert from_vectors.arrows["group"].to_list() == list(
        range(from_vectors.lines["group"].n_unique())
    )


def test_zero_field_has_no_lines() -> None:
    streams = streamplot([0, 1, 2], [0, 1], [[0, 0, 0]] * 2, [[0, 0, 0]] * 2)
    assert streams.lines.height == 0
    assert streams.arrows.height == 0


def test_renders_with_path_and_segment() -> None:
    x = [i / 10 for i in range(-20, 21)]
    u = [[-yi for _ in x] for yi in x]
    v = [[xi for xi in x] for _ in x]
    streams = streamplot(x, x, u, v, density=1.5)
    plot = (
        ggplot()
        + geom_path(aes("x", "y", group="group"), data=streams.lines)
        + geom_segment(aes("x", "y", xend="xend", yend="yend"), data=streams.arrows, arrow=arrow())
        + coord_fixed()
    )
    assert plot.to_svg().count("<path") > 0


@pytest.mark.parametrize(
    ("arguments", "path", "message"),
    [
        ({"x": [0, 1, 3]}, "x", "equally spaced"),
        ({"y": [1, 0]}, "y", "strictly increasing"),
        ({"x": [0]}, "x", "at least 2"),
        ({"u": [[0, 0]] * 2}, "u", "expected shape (2, 3)"),
        ({"density": 0.01}, "density", ">= 1/15"),
        ({"density": (1, 2, 3)}, "density", "2 numbers"),
        ({"density": 1e6}, "density", "too large"),
        ({"start_points": [[5, 0]]}, "start_points[0]", "outside the grid"),
        ({"start_points": [[0, 0, 0]]}, "start_points", "2 values"),
        ({"integration_direction": "sideways"}, "integration_direction", "accepted"),
        ({"maxlength": math.nan}, "maxlength", "finite"),
    ],
)
def test_errors(arguments: dict[str, Any], path: str, message: str) -> None:
    base: dict[str, Any] = {
        "x": [0, 1, 2],
        "y": [0, 1],
        "u": [[1, 1, 1]] * 2,
        "v": [[0, 0, 0]] * 2,
    }
    base.update(arguments)
    with pytest.raises(SpecError, match=r".") as error:
        streamplot(**base)
    assert error.value.path == path
    assert message in str(error.value)


def test_meshgrid_rows_must_match() -> None:
    with pytest.raises(SpecError, match="rows of a 2D 'x' must be equal"):
        streamplot([[0, 1], [0, 2]], [0, 1], [[1, 1]] * 2, [[0, 0]] * 2)


def test_masked_entries_are_missing() -> None:
    x = np.linspace(0, 4, 5)
    y = np.linspace(0, 3, 4)
    u = np.ones((4, 5))
    masked = np.ma.masked_array(u, mask=u * 0)
    masked[1:3, 1:3] = np.ma.masked
    with_nan = u.copy()
    with_nan[1:3, 1:3] = np.nan
    v = np.full((4, 5), 0.3)
    assert streamplot(x, y, masked, v).lines.equals(streamplot(x, y, with_nan, v).lines)
