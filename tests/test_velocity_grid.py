"""``velocity_grid()`` matches scVelo's ``compute_velocity_on_grid``.

Reference: ``tests/fixtures/velocity_grid_scvelo.json`` (generated by
``tests/fixtures/generate_velocity_grid_reference.py`` with scvelo 0.3.4): grid
axes in full, per component the NaN positions exactly and a summary of the finite
values within 1e-12 relative. On arm64 macOS the results are bit-identical; the
tolerance covers platforms where scikit-learn's distances are not FMA-contracted.
"""

from __future__ import annotations

import importlib.util
import json
import math
from pathlib import Path
from types import ModuleType
from typing import Any

import numpy as np
import pytest
from ggrust import VelocityGrid, streamplot, velocity_grid
from ggrust.errors import SpecError

FIXTURES = Path(__file__).parent / "fixtures"
TOLERANCE = 1e-12


def _generator() -> ModuleType:
    """The fixture generator, for its ``case_inputs()`` and ``summarize()``."""
    spec = importlib.util.spec_from_file_location(
        "generate_velocity_grid_reference", FIXTURES / "generate_velocity_grid_reference.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


GENERATOR = _generator()
REFERENCE: dict[str, Any] = json.loads((FIXTURES / "velocity_grid_scvelo.json").read_text())
CASES = {
    name: (points, vectors, options) for name, points, vectors, options in GENERATOR.case_inputs()
}


def _close(actual: float, expected: float, scale: float) -> bool:
    """Equal within ``TOLERANCE`` relative to ``scale``."""
    return abs(actual - expected) <= TOLERANCE * scale


@pytest.mark.parametrize("case", REFERENCE["cases"], ids=lambda case: case["name"])
def test_matches_scvelo(case: dict[str, Any]) -> None:
    points, vectors, options = CASES[case["name"]]
    grid = velocity_grid(points, vectors, **options)
    assert grid.x == case["x"]
    assert grid.y == case["y"]
    for name in ("u", "v"):
        actual = GENERATOR.summarize(np.array(getattr(grid, name)))
        expected = case[name]
        assert actual["nan_runs"] == expected["nan_runs"], name
        scale = math.sqrt(expected["sum_squares"])
        assert _close(actual["sum"], expected["sum"], scale), name
        assert _close(actual["sum_squares"], expected["sum_squares"], expected["sum_squares"])
        weighted_scale = scale * len(grid.x) ** 2
        assert _close(actual["weighted_sum"], expected["weighted_sum"], weighted_scale), name
        for (index, value), (expected_index, expected_value) in zip(
            actual["samples"], expected["samples"], strict=True
        ):
            assert index == expected_index
            assert _close(value, expected_value, abs(expected_value)), (name, index)


def test_feeds_streamplot() -> None:
    points, vectors, _ = CASES["spiral"]
    grid = velocity_grid(points, vectors)
    assert isinstance(grid, VelocityGrid)
    streams = streamplot(grid.x, grid.y, grid.u, grid.v)
    assert streams.lines.height > 0
    # nested sequences give the same grid as numpy arrays
    from_lists = velocity_grid(points.tolist(), vectors.tolist())
    assert np.array_equal(np.array(from_lists.u), np.array(grid.u), equal_nan=True)


def test_masked_and_tuple_input() -> None:
    points, vectors, _ = CASES["small"]
    masked = np.ma.masked_array(points, mask=np.zeros_like(points, dtype=bool))
    masked.mask[5, 0] = True
    expected = velocity_grid(
        np.delete(points, 5, axis=0), np.delete(vectors, 5, axis=0), n_neighbors=7
    )
    grid = velocity_grid(masked, tuple(map(tuple, vectors.tolist())), n_neighbors=7)
    assert grid.x == expected.x
    assert np.array_equal(np.array(grid.u), np.array(expected.u), equal_nan=True)


@pytest.mark.parametrize(
    ("arguments", "path", "message"),
    [
        ({"points": [[0, 1, 2]] * 60}, "points", "row 0 must hold 2 values"),
        ({"points": [["a", 1]] * 60}, "points", "holds str 'a'"),
        ({"vectors": [[0.0, 1.0]] * 59}, "vectors", "one velocity per point"),
        ({"vectors": 3}, "vectors", "expected an (n, 2) array"),
        ({"density": 0.02}, "density", "at least 0.04"),
        ({"density": "1"}, "density", "expected a number"),
        ({"smooth": -1}, "smooth", "positive"),
        ({"n_neighbors": 0}, "n_neighbors", "positive integer"),
        ({"n_neighbors": 2.5}, "n_neighbors", "positive integer"),
        ({"n_neighbors": 61}, "n_neighbors", "between 1 and the number of finite points (60)"),
        ({"cutoff_percentile": 120}, "cutoff_percentile", "between 0 and 100"),
        ({"min_mass": math.inf}, "min_mass", "finite"),
        ({"points": [[1.0, i] for i in range(60)]}, "points", "no usable spread in x"),
        ({"density": 1e9}, "density", "at most 63"),
        ({"n_neighbors": 10**30}, "n_neighbors", "positive integer"),
        ({"points": [[10**400, 1]] * 60}, "points", "too large for a float"),
        ({"points": [[1.0, 2.0]] * 60, "adjust_for_stream": False}, "points", "kernel width"),
    ],
)
def test_errors(arguments: dict[str, Any], path: str, message: str) -> None:
    points, vectors, _ = CASES["small"]
    call: dict[str, Any] = {"points": points, "vectors": vectors, "n_neighbors": 7} | arguments
    with pytest.raises(SpecError) as error:
        velocity_grid(call.pop("points"), call.pop("vectors"), **call)
    assert error.value.path == path
    assert message in str(error.value)


def test_default_neighbours_need_fifty_points() -> None:
    points, vectors, _ = CASES["small"]
    with pytest.raises(SpecError, match=r"int\(n_points / 50\) = 0") as error:
        velocity_grid(points[:49], vectors[:49])
    assert error.value.path == "n_neighbors"


def test_frames_and_flat_quiver_axis() -> None:
    import polars as pl

    points, vectors, _ = CASES["small"]
    frame = pl.DataFrame({"x": points[:, 0], "y": points[:, 1]})
    expected = velocity_grid(points, vectors, n_neighbors=7)
    assert velocity_grid(frame, vectors, n_neighbors=7).x == expected.x
    # scVelo's quiver grid accepts points without spread in one axis
    flat = np.column_stack([np.ones(60), points[:, 1]])
    grid = velocity_grid(flat, vectors, n_neighbors=7, adjust_for_stream=False)
    assert set(grid.x) == {1.0}
